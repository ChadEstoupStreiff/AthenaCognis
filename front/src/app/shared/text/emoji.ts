/**
 * Emojis whose name contains a query (prefix matches first).
 *
 * @param query - Partial shortcode.
 * @param limit - Maximum results.
 * @returns Matches.
 */
export function searchEmojis(query: string, limit: number): Emoji[] {
  const needle = query.toLowerCase();
  const prefix = EMOJIS.filter((emoji) => emoji.name.startsWith(needle));
  const inner = EMOJIS.filter(
    (emoji) => !emoji.name.startsWith(needle) && emoji.name.includes(needle),
  );
  return [...prefix, ...inner].slice(0, limit);
}
